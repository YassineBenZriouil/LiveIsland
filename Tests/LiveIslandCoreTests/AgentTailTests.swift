        #expect(odd.resumeCommand == nil)
        let upper = AgentSession(id: "/Users/me/.claude/projects/-Users-me-app/5F0C1A2B-1111-2222-3333-444455556666.jsonl",
                                 kind: .claude, project: "app", state: .idle, lastActivity: Date())
        #expect(upper.resumeCommand == "claude --resume 5F0C1A2B-1111-2222-3333-444455556666")
    }
