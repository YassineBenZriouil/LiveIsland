/// Transcript lines shaped like the ones Claude Code and Codex write around the end of a turn.
private enum TailFixture {
    static let cwd = #""cwd":"/Users/me/Code/app","sessionId":"s1","version":"2.1.331""#

    static func claudeUser(content: String, at timestamp: String, extra: String = "") -> String {
        #"{"parentUuid":"u1","isSidechain":false,"type":"user","message":{"role":"user","content":\#(content)},"uuid":"u5",\#(extra)"timestamp":"\#(timestamp)","userType":"external",\#(cwd)}"#
    }

    static func interrupt(at timestamp: String) -> String {
        claudeUser(content: #"[{"type":"text","text":"[Request interrupted by user]"}]"#, at: timestamp)
    }

    static func interruptedTool(at timestamp: String) -> String {
        claudeUser(content: #"[{"type":"tool_result","content":"[Request interrupted by user for tool use]","is_error":true,"tool_use_id":"toolu_1"}]"#, at: timestamp)
    }

    static func command(_ name: String, at timestamp: String) -> String {
        claudeUser(content: #""<command-name>/\#(name)</command-name>\n<command-message>\#(name)</command-message>\n<command-args></command-args>""#, at: timestamp)
    }

    static func commandOutput(at timestamp: String) -> String {
        claudeUser(content: #""<local-command-stdout>Set model to Opus 5.5</local-command-stdout>""#, at: timestamp)
    }

    static func caveat(at timestamp: String) -> String {
        claudeUser(content: #""<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>""#,
                   at: timestamp, extra: #""isMeta":true,"#)
    }

    static func metaPrompt(at timestamp: String) -> String {
        claudeUser(content: #"[{"type":"text","text":"Please analyze this codebase and create a CLAUDE.md file."}]"#, at: timestamp, extra: #""isMeta":true,"#)
    }

    static func systemCommand(at timestamp: String) -> String {
        #"{"parentUuid":"u4","isSidechain":false,"type":"system","subtype":"local_command","content":"<local-command-stdout>Kept model as Opus 5.5</local-command-stdout>","level":"info","timestamp":"\#(timestamp)","uuid":"u6","isMeta":false,"commandRun":{"command":"model","args":""},\#(cwd)}"#
    }

    static func apiRequest(at timestamp: String) -> String {
        #"{"type":"api-request","sessionId":"s1","id":"r1","timestamp":"\#(timestamp)","version":"2.1.331","querySource":"repl_main_thread","params":{"model":"claude-opus-5-5"}}"#
    }

    /// A subagent's progress, nesting a finished assistant message and its own timestamp.
    static func progress(at timestamp: String) -> String {
        #"{"parentUuid":"u2","isSidechain":false,"type":"progress","data":{"type":"agent_progress","message":{"type":"assistant","message":{"role":"assistant","content":[{"type":"text","text":"Found it"}],"stop_reason":"end_turn"},"timestamp":"2026-10-22T10:20:00.000Z"},"prompt":"Find the bug"},"toolUseID":"toolu_1","parentToolUseID":"toolu_1","uuid":"u7","timestamp":"\#(timestamp)",\#(cwd)}"#
    }

    static func sidechain(_ type: String, at timestamp: String) -> String {
        type == "user"
            ? #"{"parentUuid":null,"isSidechain":true,"agentId":"a1","type":"user","message":{"role":"user","content":"Audit the parser"},"uuid":"s2","timestamp":"\#(timestamp)",\#(cwd)}"#
            : #"{"parentUuid":"s2","isSidechain":true,"agentId":"a1","message":{"id":"msg_09","type":"message","role":"assistant","content":[{"type":"text","text":"All good"}],"stop_reason":"end_turn"},"type":"assistant","uuid":"s3","timestamp":"\#(timestamp)",\#(cwd)}"#
    }

    /// A tool result whose `toolUseResult` (after the line's own timestamp) holds another one.
    static func toolResultWithNestedTimestamp(at timestamp: String) -> String {
        #"{"parentUuid":"u1","isSidechain":false,"type":"user","message":{"role":"user","content":[{"tool_use_id":"toolu_1","type":"tool_result","content":"ok"}]},"uuid":"u2","timestamp":"\#(timestamp)","toolUseResult":{"type":"text","file":{"filePath":"/Users/me/log.jsonl","content":"{\"timestamp\":\"2020-01-01T00:00:00.000Z\"}"},"timestamp":"2020-01-01T00:00:00.000Z"},\#(cwd)}"#
    }

    static func toolUse(_ name: String, input: String, at timestamp: String = "2026-10-22T10:15:00.000Z") -> String {
        Fixture.claudeAssistant(at: timestamp, stop: "tool_use",
                                content: #"[{"type":"tool_use","id":"toolu_1","name":"\#(name)","input":\#(input),"caller":{"type":"direct"}}]"#)
    }

    static func answer(_ text: String, at timestamp: String = "2026-10-22T10:16:00.000Z") -> String {
        Fixture.claudeAssistant(at: timestamp, stop: "end_turn", content: #"[{"type":"text","text":"\#(text)"}]"#)
    }
}

private func date(_ text: String) -> Date { Format.date(iso8601: text)! }

@Suite("Claude Code tail: what doesn't count as working")
struct ClaudeTailStepTests {
    let prompt = Fixture.claudePrompt(at: "2026-10-22T10:14:00.000Z")
    let finished = Fixture.claudeAssistant(at: "2026-10-22T10:15:00.000Z", stop: "end_turn")

    private func tail(_ lines: [String]) -> ClaudeTranscript.Tail { ClaudeTranscript.tail(of: lines.map(Fixture.data)) }

    @Test func anInterruptEndsTheTurn() {
        let now = date("2026-10-22T10:15:03.000Z")
        let lines = [prompt, Fixture.claudeAssistant(at: "2026-10-22T10:14:30.000Z", stop: nil),
                     TailFixture.interrupt(at: "2026-10-22T10:15:00.000Z")]
        let tail = tail(lines)
        #expect(tail.lastStep == .interrupted)
        #expect(tail.lastTimestamp == date("2026-10-22T10:15:00.000Z"))
        #expect(ClaudeTranscript.state(of: tail, modified: now, now: now) == .idle, "not working, and nothing finished")
    }

    @Test func anInterruptedToolEndsTheTurnToo() {
        let lines = [prompt, Fixture.claudeAssistant(at: "2026-10-22T10:14:30.000Z"),
                     TailFixture.interruptedTool(at: "2026-10-22T10:15:00.000Z")]
        #expect(tail(lines).lastStep == .interrupted)
    }

    @Test func aPromptAfterAnInterruptStartsANewTurn() {
        let lines = [prompt, TailFixture.interrupt(at: "2026-10-22T10:15:00.000Z"),
                     Fixture.claudePrompt(at: "2026-10-22T10:16:00.000Z", text: "try again")]
        let tail = tail(lines)
        #expect(tail.lastStep == .awaitingModel)
        #expect(tail.turnStartedAt == date("2026-10-22T10:16:00.000Z"))
    }

    @Test func localCommandsAndTheirOutputLeaveTheFinishedTurnAlone() {
        let now = date("2026-10-22T10:30:02.000Z")
        let lines = [prompt, finished,
                     TailFixture.caveat(at: "2026-10-22T10:30:00.000Z"),
                     TailFixture.command("model", at: "2026-10-22T10:30:00.000Z"),
                     TailFixture.commandOutput(at: "2026-10-22T10:30:01.000Z"),
                     TailFixture.systemCommand(at: "2026-10-22T10:30:01.000Z")]
        let tail = tail(lines)
        #expect(tail.lastStep == .finished)
        #expect(tail.turnStartedAt == date("2026-10-22T10:14:00.000Z"))
        #expect(tail.lastTimestamp == date("2026-10-22T10:15:00.000Z"))
        #expect(ClaudeTranscript.state(of: tail, modified: now, now: now) == .idle,
                "the file just changed, but the turn ended long ago: no second Done")
    }

    @Test func metaLinesAreNotPrompts() {
        let lines = [prompt, finished, TailFixture.metaPrompt(at: "2026-10-22T10:30:00.000Z")]
        let tail = tail(lines)
        #expect(tail.lastStep == .finished)
        #expect(tail.turnStartedAt == date("2026-10-22T10:14:00.000Z"))
    }

    @Test func aCommandThatPromptsTheModelStartsATurnAtTheCommand() {
        let lines = [prompt, finished,
                     TailFixture.command("init", at: "2026-10-22T10:30:00.000Z"),
                     TailFixture.metaPrompt(at: "2026-10-22T10:30:00.100Z"),
                     TailFixture.apiRequest(at: "2026-10-22T10:30:00.500Z")]
        let tail = tail(lines)
        #expect(tail.lastStep == .awaitingModel)
        #expect(tail.turnStartedAt == date("2026-10-22T10:30:00.000Z"))
    }

    @Test func anAPIRequestMidTurnKeepsTheTurnStart() {
        let lines = [prompt, Fixture.claudeAssistant(at: "2026-10-22T10:14:30.000Z"), Fixture.claudeToolResult(),
                     TailFixture.apiRequest(at: "2026-10-22T10:15:06.000Z")]
        #expect(tail(lines).turnStartedAt == date("2026-10-22T10:14:00.000Z"))
    }

    @Test func subagentProgressDoesNotMoveTheParent() {
        let lines = [prompt, Fixture.claudeAssistant(at: "2026-10-22T10:14:30.000Z"),
                     TailFixture.progress(at: "2026-10-22T10:20:00.000Z")]
        let tail = tail(lines)
        #expect(tail.lastStep == .calledTool, "the nested end_turn belongs to the subagent")
        #expect(tail.lastTimestamp == date("2026-10-22T10:14:30.000Z"))
        #expect(tail.turnStartedAt == date("2026-10-22T10:14:00.000Z"))
    }

    @Test func sidechainLinesDoNotMoveTheParent() {
        let lines = [prompt, Fixture.claudeAssistant(at: "2026-10-22T10:14:30.000Z"),
                     TailFixture.sidechain("user", at: "2026-10-22T10:14:31.000Z"),
                     TailFixture.sidechain("assistant", at: "2026-10-22T10:14:40.000Z")]
        let tail = tail(lines)
        #expect(tail.lastStep == .calledTool)
        #expect(tail.turnStartedAt == date("2026-10-22T10:14:00.000Z"))
        #expect(tail.lastTimestamp == date("2026-10-22T10:14:30.000Z"))
    }

    @Test func theLinesOwnTimestampWinsOverOneInsideTheToolResult() {
        let lines = [prompt, Fixture.claudeAssistant(at: "2026-10-22T10:14:30.000Z"),
                     TailFixture.toolResultWithNestedTimestamp(at: "2026-10-22T10:15:05.000Z")]
        let tail = tail(lines)
        #expect(tail.lastTimestamp == date("2026-10-22T10:15:05.000Z"))
        #expect(tail.lastStep == .awaitingModel)
    }

    @Test func topLevelFieldsSkipNestedOnes() {
        let line = Fixture.data(TailFixture.progress(at: "2026-10-22T10:20:01.000Z"))
        let fields = ClaudeTranscript.TopLevel(line)
        #expect(fields.type == "progress")
        #expect(fields.timestamp == "2026-10-22T10:20:01.000Z")
        #expect(!fields.isSidechain)
        #expect(!fields.isMeta)
        let meta = ClaudeTranscript.TopLevel(Fixture.data(TailFixture.caveat(at: "2026-10-22T10:30:00.000Z")))
        #expect(meta.isMeta)
        #expect(meta.type == "user")
        #expect(ClaudeTranscript.TopLevel(Fixture.data(TailFixture.sidechain("user", at: "2026-10-22T10:14:31.000Z"))).isSidechain)
    }

    @Test func aTypedPromptQuotingACommandTagStillCounts() {
        let lines = [Fixture.claudePrompt(at: "2026-10-22T10:14:00.000Z", text: "why does <command-name> show up?")]
        #expect(tail(lines).lastStep == .awaitingModel)
    }
}

@Suite("Claude Code tail: what the session needs from the person")
struct ClaudeRequestTests {
    private func tail(_ lines: [String]) -> ClaudeTranscript.Tail { ClaudeTranscript.tail(of: lines.map(Fixture.data)) }

    @Test func aToolWaitingForPermissionIsNamedWithWhatItDoes() throws {
        let t = tail([Fixture.claudePrompt(), TailFixture.toolUse("Bash", input: #"{"command":"npm test","description":"Run the tests"}"#)])
        let request = try #require(ClaudeTranscript.request(of: t, state: .waiting))
        #expect(request.kind == .permission)
        #expect(request.tool == "Bash")
        #expect(request.text == "Bash: Run the tests")
        #expect(ClaudeTranscript.request(of: t, state: .working) == nil, "a tool that's running needs nobody")
    }

    @Test func editsShowTheFileName() {
        let t = tail([TailFixture.toolUse("Edit", input: #"{"file_path":"/Users/me/Code/app/Sources/Login.swift","old_string":"a","new_string":"b"}"#)])
        #expect(ClaudeTranscript.request(of: t, state: .waiting)?.text == "Edit: Login.swift")
    }

    @Test func otherToolsFallBackToACommonField() {
        let t = tail([TailFixture.toolUse("mcp__github__search", input: #"{"query":"open bugs","limit":5}"#)])
        #expect(ClaudeTranscript.request(of: t, state: .waiting)?.text == "mcp__github__search: open bugs")
        let bare = tail([TailFixture.toolUse("Mystery", input: #"{"n":1}"#)])
        #expect(ClaudeTranscript.request(of: bare, state: .waiting)?.text == "Mystery")
    }

    @Test func askUserQuestionIsAQuestion() throws {
        let input = #"{"questions":[{"question":"Which database should I use?","header":"Database","options":[{"label":"SQLite"},{"label":"Postgres"}],"multiSelect":false}]}"#
        let t = tail([Fixture.claudePrompt(), TailFixture.toolUse("AskUserQuestion", input: input)])
        let request = try #require(ClaudeTranscript.request(of: t, state: .waiting))
        #expect(request.kind == .question)
        #expect(request.text == "Which database should I use?")
    }

    @Test func aToolResultAnswersIt() {
        let t = tail([TailFixture.toolUse("Bash", input: #"{"command":"ls"}"#), Fixture.claudeToolResult()])
        #expect(t.pendingRequest == nil)
    }

    @Test func aTurnEndingOnAQuestionAsksIt() throws {
        let t = tail([Fixture.claudePrompt(), TailFixture.answer(#"I fixed the login bug.\n\nShould I push it to main?"#)])
        let request = try #require(ClaudeTranscript.request(of: t, state: .done))
        #expect(request.kind == .question)
        #expect(request.text == "Should I push it to main?")
        #expect(ClaudeTranscript.request(of: t, state: .idle) == request)
    }

    @Test func aTurnEndingOnAStatementAsksNothing() {
        let t = tail([Fixture.claudePrompt(), TailFixture.answer("Fixed. Is it what you wanted? It builds now.")])
        #expect(t.pendingRequest == nil)
    }

    @Test func aNewPromptAnswersTheQuestion() {
        let t = tail([TailFixture.answer("Should I push it?"), Fixture.claudePrompt(at: "2026-10-22T10:17:00.000Z", text: "yes")])
        #expect(t.pendingRequest == nil)
        #expect(ClaudeTranscript.request(of: t, state: .working) == nil)
    }

    @Test func longSummariesAreCutToOneLine() throws {
        let long = String(repeating: "a", count: 300)
        let request = AgentRequest(kind: .permission, tool: "Bash", summary: "first\n  " + long)
        let summary = try #require(request.summary)
        #expect(summary.count == AgentRequest.maxLength)
        #expect(summary.hasPrefix("first a"))
        #expect(summary.hasSuffix("…"))
        #expect(AgentRequest.shortened(" \n ") == nil)
        #expect(AgentRequest(kind: .question).text == "Has a question")
    }
}

@Suite("Codex tail: approvals and stops")
struct CodexTailTests {
    static func approval(at timestamp: String) -> String {
        #"{"timestamp":"\#(timestamp)","type":"event_msg","payload":{"type":"exec_approval_request","call_id":"call_1","command":["bash","-lc","npm install left-pad"],"cwd":"/Users/me/Code/api","reason":"Needs network access"}}"#
    }

    static let patchApproval = #"{"timestamp":"2026-10-16T15:30:05.000Z","type":"event_msg","payload":{"type":"apply_patch_approval_request","call_id":"call_2","changes":{"/Users/me/Code/api/src/main.rs":{"update":{"unified_diff":"@@ -1 +1 @@","move_path":null}},"/Users/me/Code/api/README.md":{"add":{"content":"API notes"}}},"reason":null,"grant_root":null}}"#

    static let customOutput = #"{"timestamp":"2026-10-16T15:30:08.000Z","type":"response_item","payload":{"type":"custom_tool_call_output","call_id":"call_2","output":"Success. Updated the following files:\nM src/main.rs"}}"#

    let started = Fixture.codexEvent("task_started", at: "2026-10-16T15:30:00.000Z")

    @Test func aStaleApprovalTimesOut() {
        let lines = [Fixture.codexMeta, started, Self.approval(at: "2026-10-16T15:30:05.000Z")]
        let tail = CodexRollout.tail(of: lines.map(Fixture.data))
        let modified = date("2026-10-16T15:30:05.000Z")
        #expect(CodexRollout.state(of: tail, modified: modified, now: modified.addingTimeInterval(60)) == .waiting)
        #expect(CodexRollout.state(of: tail, modified: modified, now: modified.addingTimeInterval(31 * 60)) == .idle)
    }

    @Test func aPatchOutputAnswersTheApproval() {
        let lines = [Fixture.codexMeta, started, Self.patchApproval, Self.customOutput]
        let tail = CodexRollout.tail(of: lines.map(Fixture.data))
        #expect(!tail.awaitingApproval)
        #expect(tail.pendingRequest == nil)
        let now = date("2026-10-16T15:30:09.000Z")
        #expect(CodexRollout.state(of: tail, modified: now, now: now) == .working)
    }

    @Test func anAbortedTurnIsIdleNotDone() {
        let lines = [Fixture.codexMeta, started, Self.approval(at: "2026-10-16T15:30:05.000Z"),
                     #"{"timestamp":"2026-10-16T15:30:07.000Z","type":"event_msg","payload":{"type":"turn_aborted","reason":"interrupted"}}"#]
        let tail = CodexRollout.tail(of: lines.map(Fixture.data))
        let now = date("2026-10-16T15:30:08.000Z")
        #expect(!tail.working)
        #expect(!tail.awaitingApproval)
        #expect(CodexRollout.state(of: tail, modified: now, now: now) == .idle)
        #expect(tail.lastEventAt == date("2026-10-16T15:30:07.000Z"))
    }

    @Test func theApprovalSaysWhatItsFor() throws {
        let command = CodexRollout.tail(of: [started, Self.approval(at: "2026-10-16T15:30:05.000Z")].map(Fixture.data))
        let request = try #require(CodexRollout.request(of: command, state: .waiting))
        #expect(request.kind == .permission)
        #expect(request.text == "Command: npm install left-pad")
        #expect(CodexRollout.request(of: command, state: .idle) == nil)

        let patch = CodexRollout.tail(of: [started, Self.patchApproval].map(Fixture.data))
        #expect(CodexRollout.request(of: patch, state: .waiting)?.text == "Edit: README.md, main.rs")
    }
}

@Suite struct ResumeSafetyTests {
    @Test func aClaudeSessionIDMustBeAUUID() {
        let odd = AgentSession(id: "/Users/me/.claude/projects/-Users-me-app/x$(touch pwned).jsonl",
                               kind: .claude, project: "app", state: .idle, lastActivity: Date(), cwd: "/Users/me/app")
